#!/usr/bin/env python3
"""Turn the Stand-In design tokens, icons and fonts into each client's native theme.

    generate.py --android <android app/src/main/res>
    generate.py --qml <desktop client app/>

Everything written is generated: edit tokens.json / ../icons / ../fonts instead.
"""
import argparse
import json
import re
import shutil
import xml.etree.ElementTree as ET
from pathlib import Path

HERE = Path(__file__).resolve().parent
BRAND = HERE.parent
HEADER = "Generated by stand-in-brand/design/generate.py from tokens.json. Don't edit."
WEIGHTS = {"regular": "Regular", "medium": "Medium", "semibold": "SemiBold", "bold": "Bold"}


def load():
    tokens = json.loads((HERE / "tokens.json").read_text())
    return tokens, tokens["themes"][tokens["defaultTheme"]]


def snake(name):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


# ---- Android ---------------------------------------------------------------

def svg_to_vector(svg_path):
    """Convert one of our stroke icons (path/circle/rect only) to an Android vector."""
    ns = {"s": "http://www.w3.org/2000/svg"}
    root = ET.parse(svg_path).getroot()
    stroke_width = root.get("stroke-width", "1.5")
    out = [
        '<?xml version="1.0" encoding="utf-8"?>',
        f"<!-- {HEADER} -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    android:width="24dp" android:height="24dp"',
        '    android:viewportWidth="24" android:viewportHeight="24">',
    ]
    for el in root:
        tag = el.tag.split("}")[-1]
        if tag == "path":
            d = el.get("d")
        elif tag == "circle":
            cx, cy, r = (float(el.get(k)) for k in ("cx", "cy", "r"))
            d = f"M{cx - r:g},{cy:g}a{r:g},{r:g} 0 1,0 {2 * r:g},0a{r:g},{r:g} 0 1,0 {-2 * r:g},0z"
        elif tag == "rect":
            x, y, w, h = (float(el.get(k)) for k in ("x", "y", "width", "height"))
            r = float(el.get("rx", 0))
            d = (f"M{x + r:g},{y:g}h{w - 2 * r:g}a{r:g},{r:g} 0 0,1 {r:g},{r:g}v{h - 2 * r:g}"
                 f"a{r:g},{r:g} 0 0,1 {-r:g},{r:g}h{-(w - 2 * r):g}a{r:g},{r:g} 0 0,1 {-r:g},{-r:g}"
                 f"v{-(h - 2 * r):g}a{r:g},{r:g} 0 0,1 {r:g},{-r:g}z")
        else:
            raise SystemExit(f"{svg_path.name}: unsupported element <{tag}>")

        filled = el.get("fill") not in (None, "none") and el.get("stroke") == "none"
        if filled:
            out.append(f'    <path android:fillColor="@color/si_text" android:pathData="{d}" />')
        else:
            out.append(f'    <path android:strokeColor="@color/si_text" android:strokeWidth="{stroke_width}"'
                       f' android:strokeLineCap="round" android:strokeLineJoin="round" android:pathData="{d}" />')
    out.append("</vector>")
    return "\n".join(out) + "\n"


def android(res):
    tokens, theme = load()
    res = Path(res)

    lines = ['<?xml version="1.0" encoding="utf-8"?>', f"<!-- {HEADER} -->", "<resources>"]
    for name, value in theme.items():
        lines.append(f'    <color name="si_{snake(name)}">{value}</color>')
    for group in ("space", "radius", "size"):
        for name, value in tokens[group].items():
            lines.append(f'    <dimen name="si_{group}_{snake(name)}">{value}dp</dimen>')
    for name, style in tokens["type"].items():
        lines.append(f'    <dimen name="si_text_{snake(name)}">{style["size"]}sp</dimen>')
    lines.append(f'    <integer name="si_motion_fast">{tokens["motion"]["fast"]}</integer>')
    lines.append(f'    <integer name="si_motion_normal">{tokens["motion"]["normal"]}</integer>')
    lines.append(f'    <integer name="si_motion_page">{tokens["motion"]["page"]}</integer>')
    lines.append("</resources>")
    (res / "values").mkdir(parents=True, exist_ok=True)
    (res / "values" / "si_tokens.xml").write_text("\n".join(lines) + "\n")

    # Text appearances, one per type style
    styles = ['<?xml version="1.0" encoding="utf-8"?>', f"<!-- {HEADER} -->", "<resources>"]
    for name, style in tokens["type"].items():
        styles += [
            f'    <style name="SiText.{name[0].upper() + name[1:]}" parent="">',
            f'        <item name="android:textSize">{style["size"]}sp</item>',
            f'        <item name="android:fontFamily">@font/inter_{style["weight"]}</item>',
            f'        <item name="fontFamily">@font/inter_{style["weight"]}</item>',
            f'        <item name="android:textColor">@color/si_text</item>',
            "    </style>",
        ]
    styles.append("</resources>")
    (res / "values" / "si_type.xml").write_text("\n".join(styles) + "\n")

    (res / "font").mkdir(exist_ok=True)
    for key, file_weight in WEIGHTS.items():
        shutil.copy(BRAND / "fonts" / f"Inter-{file_weight}.ttf", res / "font" / f"inter_{key}.ttf")

    (res / "drawable").mkdir(exist_ok=True)
    for svg in sorted((BRAND / "icons").glob("*.svg")):
        (res / "drawable" / f"ic_si_{svg.stem.replace('-', '_')}.xml").write_text(svg_to_vector(svg))


# ---- Desktop (QML) ---------------------------------------------------------

def qml(app):
    tokens, theme = load()
    app = Path(app)

    def prop(kind, name, value):
        return f"    readonly property {kind} {name}: {value}"

    lines = [
        f"// {HEADER}",
        "pragma Singleton",
        "import QtQuick",
        "",
        "QtObject {",
    ]
    for name, value in theme.items():
        # QML treats "onX" properties as signal handlers
        if re.match(r"on[A-Z]", name):
            name = "textOn" + name[2:]
        lines.append(prop("color", name, f'"{value}"'))
    lines.append("")
    for name, color in tokens["status"].items():
        lines.append(prop("color", "status" + name[0].upper() + name[1:], color))
    lines.append("")
    lines.append(prop("string", "fontFamily", f'"{tokens["font"]["family"]}"'))
    for name, style in tokens["type"].items():
        weight = {"regular": "Font.Normal", "medium": "Font.Medium",
                  "semibold": "Font.DemiBold", "bold": "Font.Bold"}[style["weight"]]
        lines.append(prop("font", name,
                          f'Qt.font({{ family: "{tokens["font"]["family"]}", pixelSize: {style["size"]}, weight: {weight} }})'))
    lines.append("")
    for group in ("space", "radius", "size"):
        for name, value in tokens[group].items():
            lines.append(prop("int", group + name[0].upper() + name[1:], value))
    for name, value in tokens["motion"].items():
        lines.append(prop("int", "motion" + name[0].upper() + name[1:], value))
    lines.append("")
    lines.append('    function icon(name) { return "qrc:/res/si/" + name + ".svg" }')
    lines.append("}")
    (app / "gui" / "Theme.qml").write_text("\n".join(lines) + "\n")

    icons = app / "res" / "si"
    icons.mkdir(parents=True, exist_ok=True)
    for svg in sorted((BRAND / "icons").glob("*.svg")):
        shutil.copy(svg, icons / svg.name)

    fonts = app / "res" / "fonts"
    fonts.mkdir(exist_ok=True)
    for file_weight in WEIGHTS.values():
        shutil.copy(BRAND / "fonts" / f"Inter-{file_weight}.ttf", fonts)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--android")
    parser.add_argument("--qml")
    args = parser.parse_args()
    if args.android:
        android(args.android)
    if args.qml:
        qml(args.qml)
